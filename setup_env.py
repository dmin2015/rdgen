"""Interactive helper for setup_dev.bat.

Reads the rdgen configuration from the user and writes the .env file.

The prompts live here rather than in the batch file because cmd's "set /p"
consumes the whole stdin buffer, which breaks when the answers are piped in
instead of typed. Python's input() reads line by line and behaves the same
in both cases.
"""

import os
import sys


def ask(prompt, default):
    """Prompt for a value, returning default when the answer is empty."""
    try:
        answer = input(f"{prompt} [{default}]: ").strip()
    except EOFError:
        print()
        answer = ""
    return answer or default


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    env_path = os.path.join(here, ".env")

    print()
    print("=== rdgen setup ===")
    print()
    print("Press Enter to accept the default in brackets.")
    print()

    ghuser = ask("GitHub account that owns the repo", "dmin2015")
    reponame = ask("Repository name", "rdgen")
    ghbranch = ask("Branch to build from", "master")

    print()
    print("The GitHub PAT needs the \"workflow\" scope on the repository above.")
    print("Create one at: https://github.com/settings/tokens")
    ghbearer = ask("GitHub PAT (leave empty to fill in later)", "")

    genurl = ask("Base URL for the generated client", "http://127.0.0.1:8000")
    protocol = ask("Scheme for that URL - http or https", "http")
    zippassword = ask(
        "Secrets zip password (must match the GitHub ZIP_PASSWORD secret)", "insecure"
    )
    rdgen_port = ask("Local server port", "8000")

    lines = [
        "# Generated by setup_dev.bat - never commit this file.",
        f"GHUSER={ghuser}",
        f"REPONAME={reponame}",
        f"GHBRANCH={ghbranch}",
        f"GHBEARER={ghbearer}",
        f"GENURL={genurl}",
        f"PROTOCOL={protocol}",
        f"ZIP_PASSWORD={zippassword}",
        "RDGEN_HOST=127.0.0.1",
        f"RDGEN_PORT={rdgen_port}",
    ]
    with open(env_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")

    print()
    print("[rdgen] wrote .env (PAT kept out of this script and out of git).")
    if not ghbearer:
        print("[rdgen] NOTE: GHBEARER is empty - edit .env before starting a build.")
    print("[rdgen] next: run start_dev.bat")
    print()
    return 0


if __name__ == "__main__":
    sys.exit(main())
